/// Fixed component sizes (A65 N1), so screens don't hard-code them.
abstract final class FbSize {
  /// A letter or icon avatar (the account card).
  static const double avatar = 44;

  /// A tinted square holding an icon (first-run benefit rows).
  static const double iconTile = 36;

  /// A small icon inside a tile or a button.
  static const double iconSmall = 20;

  /// The gap between a title and its second line in a compact text block.
  static const double lineGap = 2;
}
