    public static string Normalize(string input)
    {
        var folded = new StringBuilder(input.Length);
        foreach (var rune in input.EnumerateRunes())
        {
            var code = rune.Value;
            if (code is >= 0xFF01 and <= 0xFF5E) { code -= 0xFEE0; }
            if (code is 0x00AD or 0x061C or >= 0x200B and <= 0x200F or >= 0x202A and <= 0x202E
                or 0x2060 or >= 0x2066 and <= 0x2069 or 0xFEFF or 0x0027 or 0x0060 or 0x02BC or 0x2018 or 0x2019
                or >= 0x064B and <= 0x065F or 0x0670 or >= 0x06D6 and <= 0x06ED or 0x0640 or >= 0x0300 and <= 0x036F) { continue; }
            if (code is >= 0x0660 and <= 0x0669) { code += 0x30 - 0x0660; }
            if (code is >= 0x06F0 and <= 0x06F9) { code += 0x30 - 0x06F0; }
            if (code is >= 0x41 and <= 0x5A) { code += 32; }
            if (Folds.TryGetValue(code, out var replacement)) { folded.Append(replacement); }
            else { folded.Append(code is >= 0x61 and <= 0x7A or >= 0x30 and <= 0x39 or 0x20 or >= 0x0621 and <= 0x063A or >= 0x0641 and <= 0x064A ? (char)code : ' '); }
        }
        var value = folded.ToString();
        var result = new StringBuilder(value.Length);
        for (var start = 0; start < value.Length;)
        {
            var end = start + 1; var code = value[start];
            while (end < value.Length && value[end] == code) { end++; }
            var collapse = code is >= 'a' and <= 'z' or 'ا' or 'و' or 'ي' or ' ' || end - start >= 3 && code is >= '\u0621' and <= '\u064A';
            result.Append(code, collapse ? 1 : end - start); start = end;
        }
        return result.ToString().Trim(' ');
    }
