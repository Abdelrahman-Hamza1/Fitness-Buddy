/// The pack rows of a few items as one SQL script (A05 D7): the committed
/// fixture of the app's unit tests (`apps/mobile/test/fixtures/
/// catalog_fixture.sql`). It creates the pack schema and inserts the rows of
/// [ids] (basics, or dishes with their variants), their names and servings,
/// and all yields. A test regenerates it from `data/` and compares, so the
/// fixture can't drift from the real pack.
String packFixtureSql(Release release, Set<String> ids) {
  final dishIds = {
    for (final r in release.table('dishes'))
      if (ids.contains(r['id'])) r['id']! as String,
  };
  final foodIds = {
    for (final r in release.table('foods'))
      if (ids.contains(r['id']) || dishIds.contains(r['dish_id']))
        r['id']! as String,
  };
  final unknown = ids.difference({...foodIds, ...dishIds});
  if (unknown.isNotEmpty) {
    throw ArgumentError('not in the release: ${unknown.join(', ')}');
  }
  bool keep(String table, Map<String, Object?> row) => switch (table) {
    'foods' => foodIds.contains(row['id']),
    'dishes' => dishIds.contains(row['id']),
    'names' =>
      foodIds.contains(row['target_id']) || dishIds.contains(row['target_id']),
    'servings' => foodIds.contains(row['food_id']),
    'yields' => true,
    _ => false,
  };
  final b = StringBuffer()
    ..writeln('-- Generated by `catalog emit-sql`; do not edit (A05 D7).')
    ..write(packDdl)
    ..writeln('BEGIN;');
  for (final MapEntry(key: table, value: columns) in packColumns.entries) {
    for (final row in release.table(table).where((r) => keep(table, r))) {
      final values = [for (final c in columns) _literal(_cell(row, c))];
      b.writeln(
        'INSERT INTO $table (${columns.join(', ')}) '
        'VALUES (${values.join(', ')});',
      );
    }
  }
  b
    ..writeln(
      'INSERT INTO names_fts (rowid, key) SELECT rowid, key FROM names;',
    )
    ..writeln(
      "INSERT INTO meta VALUES ('attribution', '[]'), "
      "('catalog_version', '1'), ('content_sha256', 'fixture'), "
      "('includes_drafts', '${release.includesDrafts ? 1 : 0}'), "
      "('schema_version', '$schemaVersion');",
    )
    ..writeln('COMMIT;')
    ..writeln('PRAGMA user_version = $schemaVersion;');
  return b.toString();
}

Object? _cell(Map<String, Object?> row, String column) {
  if (column != 'extras_json') return row[column];
  final extras = row['extras'];
  return extras == null ? null : jsonEncode(extras);
}

String _literal(Object? v) => switch (v) {
  null => 'NULL',
  true => '1',
  false => '0',
  final num n => '$n',
  _ => "'${'$v'.replaceAll("'", "''")}'",
};
