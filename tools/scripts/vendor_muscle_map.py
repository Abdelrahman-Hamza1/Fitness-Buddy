#!/usr/bin/env python3
"""Vendors the male front/back body paths of react-native-body-highlighter
(MIT) into packages/fb_design_system as a Dart const table (A37 D16).

Usage:
  git clone https://github.com/HichamELBSI/react-native-body-highlighter.git /tmp/rnbh
  git -C /tmp/rnbh checkout <commit>
  python3 -I tools/scripts/vendor_muscle_map.py /tmp/rnbh

Only the male `assets/bodyFront.ts` and `assets/bodyBack.ts` are read. The
path strings are copied verbatim; the upstream slugs are mapped to
`FbBodyRegion` (non-muscle parts such as head, hands and knees, and muscles
outside the app's vocabulary such as tibialis, become the neutral body).
Provenance and licence: packages/fb_design_system/assets/licenses/SOURCES.md.
"""

from __future__ import annotations

import pathlib
import re
import subprocess
import sys

# Upstream slug -> FbBodyRegion value; None = drawn as the neutral body.
REGIONS: dict[str, str | None] = {
    "chest": "chest",
    "deltoids": "deltoids",
    "biceps": "biceps",
    "triceps": "triceps",
    "forearm": "forearms",
    "trapezius": "trapezius",
    "upper-back": "upperBack",
    "lower-back": "lowerBack",
    "abs": "abs",
    "obliques": "obliques",
    "quadriceps": "quadriceps",
    "hamstring": "hamstrings",
    "gluteal": "glutes",
    "calves": "calves",
    "adductors": "adductors",
    "head": None,
    "hair": None,
    "neck": None,
    "hands": None,
    "feet": None,
    "knees": None,
    "ankles": None,
    "tibialis": None,
}

OUT = pathlib.Path(__file__).resolve().parents[2] / (
    "packages/fb_design_system/lib/src/components/muscle_map_paths.dart"
)

SLUG = re.compile(r'slug:\s*"([a-z-]+)"')
PATH = re.compile(r'"([Mm][^"]*)"')


def parts(ts: str) -> list[tuple[str | None, str]]:
    chunks = SLUG.split(ts)
    out: list[tuple[str | None, str]] = []
    # chunks = [preamble, slug1, body1, slug2, body2, ...]
    for slug, body in zip(chunks[1::2], chunks[2::2]):
        if slug not in REGIONS:
            raise SystemExit(f"unknown upstream slug: {slug}")
        region = REGIONS[slug]
        for d in PATH.findall(body):
            if "'" in d or "\\" in d or "$" in d:
                raise SystemExit(f"unexpected character in a path of {slug}")
            out.append((region, d))
    return out


def dart_list(name: str, doc: str, items: list[tuple[str | None, str]]) -> str:
    lines = [f"/// {doc}", f"const List<(FbBodyRegion?, String)> {name} = ["]
    for region, d in items:
        r = f"FbBodyRegion.{region}" if region else "null"
        lines.append(f"  ({r}, '{d}'),")
    lines.append("];")
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: vendor_muscle_map.py <react-native-body-highlighter checkout>")
    repo = pathlib.Path(sys.argv[1])
    commit = subprocess.run(
        ["git", "-C", str(repo), "rev-parse", "HEAD"],
        check=True, capture_output=True, text=True,
    ).stdout.strip()
    front = parts((repo / "assets/bodyFront.ts").read_text(encoding="utf-8"))
    back = parts((repo / "assets/bodyBack.ts").read_text(encoding="utf-8"))
    header = f"""// GENERATED by tools/scripts/vendor_muscle_map.py: don't edit by hand.
// Source: https://github.com/HichamELBSI/react-native-body-highlighter
// Commit: {commit} (assets/bodyFront.ts, assets/bodyBack.ts)
// Licence: MIT, Copyright (c) 2022 ELABBASSI Hicham. Full text and
// provenance: packages/fb_design_system/assets/licenses/.
// ignore_for_file: lines_longer_than_80_chars

import 'package:fb_design_system/src/components/muscle_map.dart';
"""
    body = "\n\n".join([
        dart_list(
            "fbMuscleMapFront",
            "The front view's parts (upstream view box x 0..724, y 0..1448).",
            front,
        ),
        dart_list(
            "fbMuscleMapBack",
            "The back view's parts (upstream view box x 724..1448, y 0..1448).",
            back,
        ),
    ])
    OUT.write_text(header + "\n" + body + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(front)} front, {len(back)} back paths) from {commit}")


if __name__ == "__main__":
    main()
