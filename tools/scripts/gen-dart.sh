#!/usr/bin/env bash
# Regenerates the Dart API client in packages/fb_api_client (S02 D1, D2):
#   1. copy the bundled contract and the union fixture into .dart_tool/fb_gen/,
#      deleting `format: date` lines (swagger_parser would turn LocalDate into a
#      DateTime and send a time part; the app gets a `YYYY-MM-DD` String),
#   2. delete both generated folders (so removed schemas leave no stale files),
#   3. run swagger_parser (both schemes in swagger_parser.yaml),
#   4. write a no-lint analysis_options.yaml into each generated folder,
#   5. run build_runner (freezed, json_serializable, retrofit),
#   6. dart format the generated folders.
# The result is committed; `make gen-check` fails CI if it is stale.
# Called by `make gen-dart`, which passes DART. Usage: DART=... gen-dart.sh
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
: "${DART:?gen-dart: error: DART is not set (the Makefile passes it)}"

pkg="$repo_root/packages/fb_api_client"
work="$pkg/.dart_tool/fb_gen"
generated_dirs=(lib/src/generated test/generated)

die() { echo "gen-dart: error: $*" >&2; exit 1; }

# --- 1. Generation inputs, with `format: date` stripped (D2) -----------------
rm -rf "$work"
mkdir -p "$work"
strip_date_format() { # <source> <destination>
  [[ -f "$1" ]] || die "missing input $1"
  # Anchored to a whole block-style line, so `format: date-time` survives.
  sed -E '/^[[:space:]]*format:[[:space:]]*date[[:space:]]*$/d' "$1" >"$2"
  # Any other spelling (flow style, quotes) would slip through: fail loudly.
  if grep -nE "format[\"']?[[:space:]]*:[[:space:]]*[\"']?date[\"']?[[:space:]]*([,}#]|$)" "$2" >&2; then
    die "'format: date' is still in $(basename "$2") after the strip (lines above). Extend the strip in $0."
  fi
}
strip_date_format "$repo_root/contracts/openapi.yaml" "$work/openapi.yaml"
strip_date_format "$pkg/test/fixtures/union_fixture.openapi.yaml" "$work/union_fixture.openapi.yaml"

cd "$pkg"

# --- 2. + 3. Clean output, run swagger_parser ---------------------------------
for dir in "${generated_dirs[@]}"; do rm -rf "$dir"; done
echo "gen-dart: swagger_parser"
"$DART" run swagger_parser

# --- 4. Generated code is exempt from lints but still checked for errors ------
# Its own analysis_options.yaml (no include) rather than `analyzer: exclude`,
# which would also hide compile errors.
for dir in "${generated_dirs[@]}"; do
  [[ -d "$dir" ]] || die "swagger_parser did not create $dir"
  cat >"$dir/analysis_options.yaml" <<'EOF'
# GENERATED by tools/scripts/gen-dart.sh (`make gen`). Do not edit.
# Generated code gets no lint rules (no include of the workspace rules), but the
# analyzer still reports compile errors and warnings in it.
EOF
done

# --- 5. freezed / json_serializable / retrofit --------------------------------
echo "gen-dart: build_runner"
# (build_runner 2.16 always replaces conflicting outputs: the old
# --delete-conflicting-outputs flag is gone.)
"$DART" run build_runner build

# --- 6. Format ------------------------------------------------------------------
"$DART" format "${generated_dirs[@]}" | tail -n 1
echo "gen-dart: wrote packages/fb_api_client/{lib/src/generated,test/generated}"
