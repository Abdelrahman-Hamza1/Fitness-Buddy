"""Unit tests for check-pub-lock.py (backlog #9)."""

import importlib.util
import pathlib
import unittest

_SPEC = importlib.util.spec_from_file_location(
    "check_pub_lock", pathlib.Path(__file__).with_name("check-pub-lock.py")
)
assert _SPEC is not None and _SPEC.loader is not None
check_pub_lock = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(check_pub_lock)

_HASH = "a" * 64


def _lock(*entries: str) -> str:
    return "# Generated by pub\npackages:\n" + "".join(entries) + 'sdks:\n  dart: ">=3.0.0"\n'


def _hosted(name: str, url: str = "https://pub.dev", sha: str = _HASH) -> str:
    return (
        f"  {name}:\n    dependency: transitive\n    description:\n"
        f'      name: {name}\n      sha256: "{sha}"\n      url: "{url}"\n'
        f'    source: hosted\n    version: "1.0.0"\n'
    )


_SDK = '  flutter:\n    dependency: "direct main"\n    description: flutter\n    source: sdk\n    version: "0.0.0"\n'
_GIT = (
    "  evil:\n    dependency: transitive\n    description:\n"
    '      path: "."\n      ref: main\n      url: "https://example.com/evil.git"\n'
    '    source: git\n    version: "1.0.0"\n'
)


class CheckPubLockTest(unittest.TestCase):
    def test_pub_dev_and_sdk_pass(self) -> None:
        self.assertEqual(check_pub_lock.check(_lock(_hosted("a"), _SDK)), [])

    def test_other_host_fails(self) -> None:
        problems = check_pub_lock.check(_lock(_hosted("a", url="https://pub.example.com")))
        self.assertEqual(len(problems), 1)
        self.assertIn("a: hosted url", problems[0])

    def test_git_source_fails(self) -> None:
        problems = check_pub_lock.check(_lock(_hosted("a"), _GIT))
        self.assertEqual(len(problems), 1)
        self.assertIn("evil: source 'git'", problems[0])

    def test_missing_hash_fails(self) -> None:
        problems = check_pub_lock.check(_lock(_hosted("a", sha="")))
        self.assertIn("a: missing or malformed sha256", problems)

    def test_empty_file_fails(self) -> None:
        self.assertTrue(check_pub_lock.check("# nothing\n"))

    def test_repo_lock_passes(self) -> None:
        lock = pathlib.Path(__file__).resolve().parents[2] / "pubspec.lock"
        self.assertEqual(check_pub_lock.check(lock.read_text(encoding="utf-8")), [])


if __name__ == "__main__":
    unittest.main()
